function applyCryptoScreenerTranslations(){
  var T=TRANSLATIONS[currentLang]||TRANSLATIONS.en;
  var stats=document.querySelectorAll('#statsbar-density .stat-lbl');
  if(stats[0]) stats[0].textContent=T.total_densities;
  if(stats[3]) stats[3].textContent=T.pairs_active;

  function activeValue(menuId,valueId,map){
    var active=document.querySelector('#'+menuId+' .fdd-item.active');
    var value=document.getElementById(valueId);
    if(active&&value&&map[active.dataset.val]) value.textContent=map[active.dataset.val];
  }
  activeValue('fdd-exchange-menu','fdd-exchange-val',{all:T.val_all});
  activeValue('fdd-market-menu','fdd-market-val',{all:T.val_all,perp:T.val_perp,spot:T.val_spot});
  activeValue('fdd-side-menu','fdd-side-val',{all:T.val_all,bid:T.val_bid,ask:T.val_ask});

  var screenerSettings=document.querySelector('#ch-scr-menu-btn > span');
  if(screenerSettings) screenerSettings.textContent=T.scr_settings||T.ch_params_btn||'Settings';
  document.querySelectorAll('.arb-cards-empty').forEach(function(el){var next=T.arb_no_active||'No active pairs';if(el.textContent!==next)el.textContent=next;});

  var stableKeys=['mode','quote_currencies','exchanges','sort','distance_pct','wall_age','min_size','card_style','sound','coin_list','ssp_thresholds','ssp_minvol','sound_notif'];
  var reverse={};
  Object.keys(TRANSLATIONS).forEach(function(lang){
    stableKeys.forEach(function(key){var v=TRANSLATIONS[lang]&&TRANSLATIONS[lang][key];if(v)reverse[String(v).trim()]=key;});
  });
  document.querySelectorAll('.sp-section-title,#splash-sp-panel .ssp-sec-title').forEach(function(el){
    var key=el.dataset.stableI18n||reverse[el.textContent.trim()];
    if(key){el.dataset.stableI18n=key;if(T[key])el.textContent=T[key];}
  });
  applyFormationNoteTranslations();
}

