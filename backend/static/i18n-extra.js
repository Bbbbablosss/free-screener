function applyFormationNoteTranslations(){
  var target=formationNotePrefixes[currentLang]||formationNotePrefixes.en;
  document.querySelectorAll('.fm-card-note').forEach(function(el){
    var kind=el.dataset.fmNoteKind||'',suffix=el.dataset.fmNoteValue||'';
    if(!kind){
      var text=el.textContent||'';
      Object.keys(formationNotePrefixes).some(function(lang){
        return ['level','trend'].some(function(candidate){
          var prefix=formationNotePrefixes[lang][candidate];
          if(text.indexOf(prefix)===0){kind=candidate;suffix=text.slice(prefix.length);return true;}
          return false;
        });
      });
      if(kind){el.dataset.fmNoteKind=kind;el.dataset.fmNoteValue=suffix;}
    }
    if(kind&&target[kind]){
      var next=target[kind]+suffix;
      if(el.textContent!==next)el.textContent=next;
    }
  });
}

